#!/usr/bin/env node
/**
 * Build `src/core/preview/act-engine.generated.ts` from the Hermes repo.
 *
 * The agent drives a page in the preview with an engine that runs INSIDE the
 * page. The desktop app builds the engine's source at run time with
 * `Function.prototype.toString()`. That cannot work here: the app's JavaScript
 * is Hermes bytecode and a function has no source text. So this script does
 * the same step on the Mac and writes the source into a file as a string.
 *
 *   node scripts/vendor-preview-engine.mjs [path to the Hermes repo]
 *
 * Run it again after the desktop engine changes
 * (`apps/desktop/src/lib/preview-act/`). The Hermes repo is only read.
 */

import { mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { homedir, tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

const repo = resolve(process.argv[2] ?? join(homedir(), 'Developer/hermes-mobile'))
const entry = join(repo, 'apps/desktop/src/lib/preview-act/act-in-page.ts')
// The Hermes repo has esbuild. This repo does not need it for anything else.
const esbuild = createRequire(join(repo, 'package.json'))('esbuild')
const work = mkdtempSync(join(tmpdir(), 'preview-engine-'))
const bundle = join(work, 'engine.mjs')

try {
  await esbuild.build({
    entryPoints: [entry],
    outfile: bundle,
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    // New enough that esbuild adds no helper functions: a helper lives outside
    // the function it serves, and the engine's functions travel alone.
    target: 'es2022',
    logLevel: 'warning'
  })

  const { actEngineSource } = await import(pathToFileURL(bundle).href)
  const source = actEngineSource()

  // The engine must stand alone. A name esbuild made up for a shared helper would fail inside the page.
  if (/\b__(name|spreadValues|spreadProps|publicField|async)\b/.test(source)) {
    throw new Error('The engine source refers to a bundler helper. It would fail inside the page.')
  }

  // Prove it parses and is a function of (doc, holder, action).
  if (typeof new Function(`return ${source}`)() !== 'function') {
    throw new Error('The engine source is not a function expression.')
  }

  // The overlay that shows a person what the agent does on the page: a mark on the element it
  // clicked, the outlines of an annotation. One function that stands alone, like the engine.
  const watchBundle = join(work, 'watch.mjs')

  await esbuild.build({
    entryPoints: [join(repo, 'apps/desktop/src/lib/preview-act/watch-in-page.ts')],
    outfile: watchBundle,
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    logLevel: 'warning'
  })

  const { watchInPage } = await import(pathToFileURL(watchBundle).href)
  const watchSource = watchInPage.toString()

  if (/\b__(name|spreadValues|spreadProps|publicField|async)\b/.test(watchSource)) {
    throw new Error('The overlay source refers to a bundler helper. It would fail inside the page.')
  }

  if (typeof new Function(`return (${watchSource})`)() !== 'function') {
    throw new Error('The overlay source is not a function.')
  }

  const target = resolve(import.meta.dirname, '../src/core/preview/act-engine.generated.ts')

  writeFileSync(
    target,
    `// GENERATED by scripts/vendor-preview-engine.mjs from the Hermes repo. Do not edit by hand.\n` +
      `// Source: apps/desktop/src/lib/preview-act/ (act-in-page.ts and its kits, watch-in-page.ts).\n\n` +
      `/** The in-page engine as one expression: \`function (doc, holder, action)\`. */\n` +
      `export const ACT_ENGINE_SOURCE: string = ${JSON.stringify(source)}\n\n` +
      `/** The in-page overlay as one function: \`function (doc, holder, stage, label)\`. */\n` +
      `export const WATCH_ENGINE_SOURCE: string = ${JSON.stringify(watchSource)}\n`
  )
  console.log(`Wrote ${target} (${source.length} + ${watchSource.length} characters).`)
} finally {
  rmSync(work, { recursive: true, force: true })
}
